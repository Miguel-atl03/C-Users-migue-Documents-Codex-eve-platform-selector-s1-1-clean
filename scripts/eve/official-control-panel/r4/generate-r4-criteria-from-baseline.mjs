#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const ROOT = resolve(process.cwd());
const BASELINE = resolve(
  ROOT,
  "docs/eve/panel-control/RECTOR_R4_ACCEPTANCE_BASELINE.md",
);
const JSON_OUT = resolve(
  ROOT,
  "reports/local/rector-r4-acceptance/generated/r4-criteria.generated.json",
);
const TS_OUT = resolve(ROOT, "tests/e2e/r4-criteria-definitions.ts");
const START = "<!-- R4_CRITERIA_LITERAL_BASELINE_START -->";
const END = "<!-- R4_CRITERIA_LITERAL_BASELINE_END -->";

function sha256Text(value) {
  return createHash("sha256").update(value.normalize("NFC"), "utf8").digest("hex");
}

function parseRow(line) {
  const cells = line
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((cell) => cell.trim());
  if (cells.length !== 5 || cells[0] === "ID" || /^-+$/.test(cells[0])) return null;
  const [criterionId, rectorSection, literalText, obligationsText, fixturesText] = cells;
  return {
    criterionId,
    literalText,
    literalTextSha256: sha256Text(literalText),
    rectorSection,
    semanticObligations: obligationsText
      .split(";")
      .map((item) => item.trim())
      .filter(Boolean),
    relatedFixtureIds: fixturesText
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean),
  };
}

function parseBaseline() {
  const source = readFileSync(BASELINE, "utf8").normalize("NFC");
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start < 0 || end < 0 || end <= start) throw new Error("r4_literal_baseline_markers_missing");
  const criteria = source
    .slice(start + START.length, end)
    .split(/\r?\n/)
    .filter((line) => line.trim().startsWith("|"))
    .map(parseRow)
    .filter(Boolean);
  if (criteria.length !== 19) throw new Error(`r4_literal_baseline_expected_19_found_${criteria.length}`);
  return criteria;
}

function writeGenerated(criteria) {
  mkdirSync(dirname(JSON_OUT), { recursive: true });
  writeFileSync(
    JSON_OUT,
    JSON.stringify(
      {
        source: "docs/eve/panel-control/RECTOR_R4_ACCEPTANCE_BASELINE.md",
        excludedSource: "corpus/Diseno_Panel_Control_EVE_Runtime_40_20_MBA_Ajustado_v2_RolFuncional.docx",
        generatedAt: new Date().toISOString(),
        criteria,
      },
      null,
      2,
    ) + "\n",
  );

  const ids = criteria.map((criterion) => `  | ${JSON.stringify(criterion.criterionId)}`).join("\n");
  const body = criteria
    .map(
      (criterion) =>
        `  ${JSON.stringify({
          id: criterion.criterionId,
          literalText: criterion.literalText,
          literalTextSha256: criterion.literalTextSha256,
          rectorSection: criterion.rectorSection,
          semanticObligations: criterion.semanticObligations,
          relatedFixtureIds: criterion.relatedFixtureIds,
        })},`,
    )
    .join("\n");
  writeFileSync(
    TS_OUT,
    `// Generated by scripts/eve/official-control-panel/r4/generate-r4-criteria-from-baseline.mjs\n` +
      `// Source: docs/eve/panel-control/RECTOR_R4_ACCEPTANCE_BASELINE.md\n` +
      `export type R4CriterionId =\n${ids};\n\n` +
      `export type R4CriterionDefinition = {\n` +
      `  id: R4CriterionId;\n` +
      `  literalText: string;\n` +
      `  literalTextSha256: string;\n` +
      `  rectorSection: string;\n` +
      `  semanticObligations: string[];\n` +
      `  relatedFixtureIds: string[];\n` +
      `};\n\n` +
      `export const R4_CRITERIA: R4CriterionDefinition[] = [\n${body}\n];\n`,
  );
}

writeGenerated(parseBaseline());
